const catalog: Record<Language, typeof en> = { en, 'pt-BR': pt, ru }

export function getMessage(
  language: Language,
  key: MessageKey,
  variables: Record<string, string | number> = {},
) {
  const value = catalog[language][key]
  return typeof value === 'function' ? value(variables) : value
}
